"""Render evals/results/*.json into docs/EVALUATION_RESULTS.md."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "evals" / "results"
ORDER = ["baseline", "improved", "final"]


def fmt(v, percent=False):
    if v is None:
        return "n/a"
    return f"{v * 100:.1f} %" if percent else str(v)


def table(summaries, title):
    rows = [("Cases", "cases", False), ("Cases passed", "pass_rate", True), ("Valid outputs among succeeded tasks", "valid_output_rate", True),
            ("Recovery from injected faults", "recovery_rate", True), ("Adversarial cases with no unauthorised write", "policy_compliance", True),
            ("Unauthorised writes", "unauthorised_writes", False), ("Tool calls blocked by policy", "tools_blocked", False),
            ("Retries", "retries", False), ("Invalid model answers seen", "invalid_outputs_seen", False)]
    head = "| Metric | " + " | ".join(s["config"] for s in summaries) + " |\n|---|" + "---|" * len(summaries) + "\n"
    body = "".join(f"| {label} | " + " | ".join(fmt(s.get(key), pct) for s in summaries) + " |\n" for label, key, pct in rows)
    lat = "| Wall time per case p50 / p95 (s) | " + " | ".join(f"{s['latency_seconds']['p50']} / {s['latency_seconds']['p95']}" for s in summaries) + " |\n"
    tok = "| Tokens per task mean / p95 | " + " | ".join(f"{s['tokens_per_task']['mean']} / {s['tokens_per_task']['p95']}" for s in summaries) + " |\n"
    return f"### {title}\n\n{head}{body}{lat}{tok}\n"


def by_category(summaries):
    cats = sorted(summaries[0]["by_category"])
    head = "| Category | " + " | ".join(s["config"] for s in summaries) + " |\n|---|" + "---|" * len(summaries) + "\n"
    return head + "".join(f"| {c} | " + " | ".join(f"{s['by_category'][c]['passed']}/{s['by_category'][c]['total']}" for s in summaries) + " |\n"
                          for c in cats) + "\n"


def main():
    out = ["# Evaluation results\n", "Generated by `python -m acs.evals.report` from `evals/results/*.json`. "
           "Configurations: " + "; ".join(f"**{k}**: {v}" for k, v in __import__('acs.evals.runner', fromlist=['DESCRIPTIONS']).DESCRIPTIONS.items()) + ".\n"]
    for mode, title in (("scripted", "Scripted model (100 versioned cases, deterministic, no API cost)"), ("live", "Live local model")):
        summaries = [json.loads(p.read_text())["summary"] for c in ORDER if (p := RESULTS / f"{c}-{mode}.json").exists()]
        if not summaries:
            continue
        out.append(f"## {title}\n")
        if mode == "live":
            env = summaries[0]["environment"]
            out.append(f"Model `{env.get('model')}` served at `{env.get('base_url')}`. "
                       "Live runs drop the scripts: the model's own answers decide the outcome.\n")
        out.append(table(summaries, "Summary"))
        out.append("### Pass rate by category\n\n" + by_category(summaries))
        for s in summaries:
            if s["failed_cases"]:
                out.append(f"<details><summary>{s['config']}: {len(s['failed_cases'])} failed cases</summary>\n\n"
                           + "".join(f"- `{f['id']}`: {'; '.join(f['reasons'])}" + (f" ({f['error']})" if f.get("error") else "") + "\n"
                                     for f in s["failed_cases"]) + "\n</details>\n\n")
    (ROOT / "docs" / "EVALUATION_RESULTS.md").write_text("\n".join(out))
    print("wrote docs/EVALUATION_RESULTS.md")


if __name__ == "__main__":
    main()
